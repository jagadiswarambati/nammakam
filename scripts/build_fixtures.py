    validated_cases = []
    case_ids = set()

    for idx, c in enumerate(cases_raw):
        # Enforce unique case_id
        cid = c["case_id"]
        if cid in case_ids:
            raise ValueError(f"Duplicate case_id found: {cid}")
        case_ids.add(cid)

        # Validate with Pydantic model
        validated = EvaluationCaseSchema.model_validate(c)
        validated_cases.append(validated.model_dump())

    output_path = Path("evaluation/fixtures/cases.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(validated_cases, f, indent=2, ensure_ascii=False)

    print(f"Successfully generated and validated {len(validated_cases)} cases in {output_path}")


